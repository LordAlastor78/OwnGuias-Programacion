package ejercicio2;




public class Empleado {

    public final String nombre;
    public final String correo;

    public Empleado(String nombre, String correo) {
        this.nombre = nombre;
        this.correo = correo;
    }

    public String getNombre() {
        return nombre;
    }

    public String getCorreo() {
        return correo;
    }

    

}
